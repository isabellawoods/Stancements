public enum Alignment {
    /// Aligns the content to the left side of the screen, panel or widget.
    LEFT,
    /// Aligns the content to the right side of the screen, panel or widget.
    CENTER,
    /// Aligns the content to the center of the screen, panel or widget.
    RIGHT
}
